# -*- coding: utf-8 -*-
import json

import click
import yaml

import relationship
from openapi_to_embed_relations import build_embed_mapping

"""
This script generates the route table of the kbackend data API.

It reads the generated OpenAPI document and the resources definition and emits
a Kotlin file with

  * `GeneratedDataApiRoutes.routes`: every (method, path) in the OpenAPI document, and
  * `GeneratedDataApiRoutes.embedRelations`: (parent resource, embed name) -> embedded
    resource, the same mapping as in the Go backend's embed_relations_gen.go.

The file only contains data. Which routes go to PostgREST as is, rewritten or
implemented natively is decided in Kotlin, see DataApiRegistry.kt.
"""

METHODS = ("get", "post", "patch", "delete")


def collect_routes(openapi):
    routes = []
    for path, item in openapi["paths"].items():
        if path == "/":
            continue
        for method in METHODS:
            if method in item:
                routes.append((method.upper(), path))
    routes.sort(key=lambda r: (r[1], r[0]))
    return routes


def render_kotlin(routes, embed_mapping, package):
    out = []
    out.append("// code generated by openapi_to_kbackend_routes.py -- DO NOT EDIT")
    out.append("")
    out.append(f"package {package}")
    out.append("")
    out.append("import io.ktor.http.HttpMethod")
    out.append("import no.elhub.flex.api.routes.data.ApiRoute")
    out.append("")
    out.append(
        "/** The routes and embed relations of the data API, generated from the OpenAPI document. */"
    )
    out.append("object GeneratedDataApiRoutes {")
    out.append("    val routes: List<ApiRoute> = listOf(")
    for method, path in routes:
        out.append(f'        ApiRoute(HttpMethod.{method.capitalize()}, "{path}"),')
    out.append("    )")
    out.append("")
    out.append("    val embedRelations: Map<String, Map<String, String>> = mapOf(")
    for parent in sorted(embed_mapping):
        out.append(f'        "{parent}" to mapOf(')
        for name in sorted(embed_mapping[parent]):
            out.append(f'            "{name}" to "{embed_mapping[parent][name]}",')
        out.append("        ),")
    out.append("    )")
    out.append("}")
    print("\n".join(out))


@click.command()
@click.option("--openapi", "openapi_file", required=True, help="OpenAPI JSON document")
@click.option("--resources", "resources_file", required=True, help="resources.yml")
@click.option("--module", default="api", help="Resources module (api, grid, ...)")
@click.option("--package", required=True, help="Kotlin package to emit")
def main(openapi_file, resources_file, module, package):
    with open(openapi_file) as f:
        openapi = json.load(f)
    with open(resources_file) as f:
        resources = yaml.safe_load(f)["resources"]

    rels = relationship.collect(resources, module=module)
    render_kotlin(collect_routes(openapi), build_embed_mapping(rels), package)


if __name__ == "__main__":
    main()
